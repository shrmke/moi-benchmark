def _build_units(config: CampaignConfig, candidates: Sequence[PackageCandidate]) -> list[CampaignUnit]:
    units: list[CampaignUnit] = []
    ordinal = 0
    for candidate in candidates:
        for platform in PLATFORM_ORDER:
            ordinal += 1
            unit_id = _safe_slug(f"{ordinal:03d}-{candidate.dataset}-{candidate.condition}-{platform}", 120)
            run_id = _safe_slug(f"{config.campaign_id}-{unit_id}", 160)
            units.append(
                CampaignUnit(
                    ordinal=ordinal,
                    unit_id=unit_id,
                    dataset=candidate.dataset,
                    condition=candidate.condition,
                    platform=platform,
                    system=platform,
                    package=candidate.package_root,
                    manifest=candidate.manifest_path,
                    run_id=run_id,
                    runner_output_root=Path(config.output_root) / unit_id,
                    mllm_required=candidate.mllm_required,
                )
            )
    return units


def _write_sha256_sidecar(path: Path, digest: str) -> None:
    sidecar = path.with_name(path.name + ".sha256")
    encoded = f"{digest}  {path.name}\n".encode("utf-8")
    with tempfile.NamedTemporaryFile("wb", dir=sidecar.parent, prefix=f".{sidecar.name}.", delete=False) as handle:
        temporary = Path(handle.name)
        handle.write(encoded)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, sidecar)


class CampaignStore:
    def __init__(self, config: CampaignConfig):
        self.config = config
        self.path = Path(config.checkpoint)
        self.progress_path = Path(config.progress_log)
        self.data: dict[str, Any] = self._load()

    def _load(self) -> dict[str, Any]:
        payload = _load_json(self.path)
        if payload is None:
            return {}
        if not isinstance(payload, dict) or payload.get("schema") != CHECKPOINT_SCHEMA:
            raise CampaignError(f"CHECKPOINT_INVALID:{self.path}")
        return payload

    def write(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        encoded = (json.dumps(self.data, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")
        with tempfile.NamedTemporaryFile("wb", dir=self.path.parent, prefix=f".{self.path.name}.", delete=False) as handle:
            temp_path = Path(handle.name)
            handle.write(encoded)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_path, self.path)
        _write_sha256_sidecar(self.path, hashlib.sha256(encoded).hexdigest())

    def event(self, event: str, **fields: Any) -> None:
        payload = {"schema": PROGRESS_SCHEMA, "at": _utc_now(), "event": event, **fields}
        self.progress_path.parent.mkdir(parents=True, exist_ok=True)
        with self.progress_path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(_safe_public(payload), ensure_ascii=False, sort_keys=True) + "\n")
            handle.flush()
            os.fsync(handle.fileno())
        _write_sha256_sidecar(
            self.progress_path,
            hashlib.sha256(self.progress_path.read_bytes()).hexdigest(),
        )

    def sync_plan(self, plan: dict[str, Any]) -> dict[str, Any]:
        old_units = self.data.get("units", [])
        if isinstance(old_units, dict):
            old_by_id = {str(key): dict(value) for key, value in old_units.items() if isinstance(value, Mapping)}
        else:
            old_by_id = {str(value.get("unit_id")): dict(value) for value in old_units if isinstance(value, Mapping) and value.get("unit_id")}

        units: list[dict[str, Any]] = []
        for unit in plan["units"]:
            current = dict(unit)
            previous = old_by_id.get(str(unit["unit_id"]), {})
            for key in (
                "status", "result", "preflight", "started_at", "completed_at",
                "attempts", "error", "run_id", "runner_artifact_root", "base_run_id",
                "provider_audit", "provider_audit_initial", "judge", "metrics",
            ):
                if key in previous:
                    current[key] = previous[key]
            # A resumed checkpoint owns its run identity.  Rebuild every
            # operator-visible command after restoring that identity so the
            # checkpoint cannot advertise a stale run-id/artifact root from
            # the current CLI invocation.
            current_unit = CampaignUnit(
                ordinal=int(current["ordinal"]),
                unit_id=str(current["unit_id"]),
                dataset=str(current["dataset"]),
                condition=str(current["condition"]),
                platform=str(current["platform"]),
                system=str(current["system"]),
                package=Path(str(current["package"])),
                manifest=Path(str(current["manifest"])),
                run_id=str(current["run_id"]),
                runner_output_root=Path(str(current["runner_output_root"])),
                mllm_required=bool(current.get("mllm_required", True)),
            )
            current["runner_command"] = _runner_command(
                self.config,
                current_unit,
                self.config.evaluation_stage,
                dry_run=not self.config.execute,
            )
            current["provider_audit_runner_command"] = _provider_audit_command(
                self.config,
                current,
                phase="runner",
            )
            current["provider_audit_command"] = _provider_audit_command(
                self.config,
                current,
                phase="final",
            )
            current["judge_command"] = _judge_command(
                self.config,
                current,
                command="run",
                dry_run=not self.config.execute,
            )
            current["metrics_command"] = _metrics_command(self.config, current)
            current.setdefault("status", "pending")
            current.setdefault("attempts", 0)
            units.append(current)

        if not self.data:
            self.data = {
                "schema": CHECKPOINT_SCHEMA,
                "campaign_id": self.config.campaign_id,
                "created_at": _utc_now(),
                "repo_root": str(self.config.repo_root),
                "package_root": str(self.config.package_root),
                "output_root": str(self.config.output_root),
                "evaluation_order": list(EVALUATION_ORDER),
                "platform_order": list(PLATFORM_ORDER),
                "excluded_datasets": list(EXCLUDED_DATASETS),
                "policy": {
                    "download": False,
                    "provider": self.config.provider,
                    "max_competitor_services": 1,
                    "preserve_moi_containers": sorted(PROTECTED_MOI_CONTAINERS),
                },
                "active_service": None,
            }
        effective_config = plan.get("config")
        if not isinstance(effective_config, Mapping):
            effective_config = _checkpoint_config(self.config)
        self.data["config"] = dict(effective_config)
        # Keep the legacy top-level fields synchronized for operators and for
        # checkpoints produced before the nested config block was introduced.
        for key in ("repo_root", "package_root", "output_root", "campaign_id"):
            if key in effective_config:
                self.data[key] = effective_config[key]
        # A direct package path is an explicit single-package campaign.  Keep
        # the checkpoint's ordering metadata synchronized with the plan rather
        # than retaining the legacy seven-dataset default from first creation.
        self.data["evaluation_order"] = list(plan["evaluation_order"])
        self.data["platform_order"] = list(plan["platform_order"])
        self.data["excluded_datasets"] = list(plan["excluded_datasets"])
        self.data["postprocess_contract"] = dict(plan.get("postprocess_contract", {}))
        self.data["provenance"] = dict(plan.get("provenance", {}))
        self.data["units"] = units
        self.data["missing_datasets"] = list(plan["missing_datasets"])
        self.data["updated_at"] = _utc_now()
        self.data["status"] = "planned"
        self.write()
        return self.data

    def unit(self, unit_id: str) -> dict[str, Any]:
        for unit in self.data.get("units", []):
            if unit.get("unit_id") == unit_id:
                return unit
        raise CampaignError(f"CHECKPOINT_UNIT_MISSING:{unit_id}")

    def update_unit(self, unit_id: str, **fields: Any) -> dict[str, Any]:
        unit = self.unit(unit_id)
        unit.update(fields)
        self.data["updated_at"] = _utc_now()
        self.write()
        return unit

    def set_active_service(self, platform: str | None) -> None:
        self.data["active_service"] = platform
        self.data["updated_at"] = _utc_now()
        self.write()


def _safe_public(value: Any, key: str | None = None) -> Any:
    if key and re.search(r"(?:api[_-]?key|token|password|secret|authorization)", key, re.IGNORECASE):
        return "<redacted>"
    if isinstance(value, Mapping):
        return {str(k): _safe_public(v, str(k)) for k, v in value.items()}
    if isinstance(value, list):
        return [_safe_public(item) for item in value]
    if isinstance(value, tuple):
        return [_safe_public(item) for item in value]
    return value


def _extract_result(stdout: Any) -> dict[str, Any]:
    text = str(stdout or "")
    decoder = json.JSONDecoder()
    for index in range(len(text) - 1, -1, -1):
        if text[index] != "{":
            continue
        try:
            value, _ = decoder.raw_decode(text[index:])
        except json.JSONDecodeError:
            continue
        if isinstance(value, dict):
            return dict(_safe_public(value))
    return {}


def _completed_status(status: Any) -> bool:
    return str(status or "").casefold().replace("-", "_") in {
        "success",
        "completed",
    }


def _postprocess_completed(unit: Mapping[str, Any]) -> bool:
    """Require final provider audit, Judge, and metrics gates before resuming.

    New executions also persist ``provider_audit_initial``.  The final audit
    recursively covers both runner and Judge request artifacts, while the
    pre-Judge audit remains an early fail-closed boundary in ``run``.  The
    initial record is optional here for backwards compatibility with older
    completed checkpoints whose final ``provider_audit.json`` predates this
    two-phase contract.
    """

    provider_audit = unit.get("provider_audit")
    judge = unit.get("judge")
    metrics = unit.get("metrics")
    try:
        provider_audit_returncode = int(provider_audit.get("returncode", 1)) if isinstance(provider_audit, Mapping) else 1
        judge_returncode = int(judge.get("returncode", 1)) if isinstance(judge, Mapping) else 1
        metrics_returncode = int(metrics.get("returncode", 1)) if isinstance(metrics, Mapping) else 1
    except (TypeError, ValueError):
        return False
    return (
        isinstance(provider_audit, Mapping)
        and provider_audit_returncode == 0
        and str(provider_audit.get("status", "")).upper() == "PASS"
        and isinstance(judge, Mapping)
        and judge_returncode == 0
        and str(judge.get("status", "")).upper() == "COMPLETE"
        and isinstance(metrics, Mapping)
        and metrics_returncode == 0
        and str(metrics.get("status", "")).upper() == "COMPLETE"
    )


def _campaign_unit_completed(unit: Mapping[str, Any]) -> bool:
    return _completed_status(unit.get("status")) and _postprocess_completed(unit)


class ServiceController:
    def __init__(self, orchestrator: "CampaignOrchestrator"):
        self.orchestrator = orchestrator
        self.config = orchestrator.config
        self.store = orchestrator.store
        active = self.store.data.get("active_service")
        self.active = _normal_platform(active) if active else None

    def _run(self, command: list[str], platform: str, action: str) -> dict[str, Any]:
        return self.orchestrator._run_external(command, platform=platform, action=action)

    def _running(self) -> dict[str, list[str]]:
        command = ["docker", "ps", "--format", "{{.Names}}"]
        result = self.orchestrator._run_external(command, platform="host", action="inspect-running", allow_failure=True)
        if result["returncode"] != 0:
            raise CampaignError("DOCKER_INSPECTION_FAILED")
        names = [line.strip() for line in str(result.get("stdout", "")).splitlines() if line.strip()]
        found: dict[str, list[str]] = {platform: [] for platform in PLATFORM_ORDER}
        for name in names:
            for platform, spec in SERVICE_SPECS.items():
                if spec.matches_container(name):
                    found[platform].append(name)
        return {platform: names for platform, names in found.items() if names}

    def _stop(self, platform: str) -> None:
        spec = SERVICE_SPECS[platform]
        if not spec.managed:
            self.active = None
            self.store.set_active_service(None)
            return
        self._run(spec.stop_command(self.config.repo_root), platform, "stop")
        self.active = None
        self.store.set_active_service(None)
        self.store.event("service_stopped", platform=platform)

    def _start(self, platform: str) -> None:
        spec = SERVICE_SPECS[platform]
        if not spec.managed:
            raise CampaignError(f"SERVICE_EXTERNAL:{platform}")
        self._run(spec.start_command(self.config.repo_root), platform, "start")
        self.active = platform
        self.store.set_active_service(platform)
        self.store.event("service_started", platform=platform)

    def ensure(self, platform: str) -> None:
        platform = _normal_platform(platform)
        spec = SERVICE_SPECS[platform]
        if not spec.managed:
            if self.active is not None and self.active != platform:
                self._stop(self.active)
            elif self.active == platform:
                self.active = None
                self.store.set_active_service(None)
            running = self._running()
            running_competitors = [name for name in running if SERVICE_SPECS[name].managed]
            if len(running_competitors) > 1:
                raise CampaignError("COMPETITOR_CONCURRENCY_REFUSED: multiple named competitor services are running")
            if running_competitors:
                self._stop(running_competitors[0])
            self.store.event("service_external", platform=platform, reason="EXTERNAL_MOI_SERVICE")
            return
        if self.active == platform:
            # Re-check the host even when the desired service is unchanged.
            # This catches an independently started second competitor without
            # treating protected MOI containers as campaign services.
            running = self._running()
            if len(running) > 1:
                raise CampaignError("COMPETITOR_CONCURRENCY_REFUSED: multiple named competitor services are running")
            if not spec.is_reusable(running.get(platform, ())):
                self._start(platform)
            return
        if self.active is not None:
            self._stop(self.active)

        running = self._running()
        other_platforms = [name for name in running if name != platform]
        if len(running) > 1:
            raise CampaignError("COMPETITOR_CONCURRENCY_REFUSED: multiple named competitor services are running")
        if other_platforms:
            # Only the named project/container for the observed competitor is
            # stopped.  MOI parser and MatrixOne names are never in this map.
            self._stop(other_platforms[0])
        if platform in running and spec.is_reusable(running[platform]):
            self.active = platform
            self.store.set_active_service(platform)
            self.store.event("service_reused", platform=platform)
        else:
            self._start(platform)

    def stop_active(self) -> None:
        if self.active is not None:
            self._stop(self.active)


class CampaignOrchestrator:
    def __init__(self, config: CampaignConfig):
        self.config = config
        self.store = CampaignStore(config)

    def _plan(self) -> dict[str, Any]:
        candidates = discover_manifests(self.config.package_root, repo_root=self.config.repo_root)
        units = _build_units(self.config, candidates)
        available = {candidate.dataset for candidate in candidates}
        missing = [] if any(candidate.single_package for candidate in candidates) else [
            dataset for dataset in EVALUATION_ORDER if dataset not in available
        ]
        evaluation_order = (
            [candidate.dataset for candidate in candidates if candidate.single_package]
            if any(candidate.single_package for candidate in candidates)
            else list(EVALUATION_ORDER)
        )
        public_units = []
        for unit in units:
            runner_command = _runner_command(
                self.config,
                unit,
                self.config.evaluation_stage,
                dry_run=not self.config.execute,
            )
            public_unit = unit.public(runner_command)
            public_unit["provider_audit_runner_command"] = _provider_audit_command(
                self.config,
                public_unit,
                phase="runner",
            )
            public_unit["provider_audit_command"] = _provider_audit_command(
                self.config,
                public_unit,
                phase="final",
            )
            public_unit["judge_command"] = _judge_command(
                self.config,
                public_unit,
                command="run",
                dry_run=not self.config.execute,
            )
            public_unit["metrics_command"] = _metrics_command(self.config, public_unit)
            public_units.append(public_unit)

        return {
            "schema": CHECKPOINT_SCHEMA,
            "campaign_id": self.config.campaign_id,
            "config": _checkpoint_config(self.config),
            "evaluation_order": evaluation_order,
            "platform_order": list(PLATFORM_ORDER),
            "excluded_datasets": list(EXCLUDED_DATASETS),
            "postprocess_contract": {
                "schema": POSTPROCESS_CONTRACT_SCHEMA,
                "order_per_unit": list(POSTPROCESS_ORDER),
                "formal_completion_requires": [
                    "runner_status=SUCCESS",
                    "provider_audit_runner_status=PASS",
                    "judge_status=COMPLETE",
                    "provider_audit_final_status=PASS",
                    "metrics_status=COMPLETE",
                ],
            },
            "provenance": _campaign_provenance(self.config, candidates),
            "missing_datasets": missing,
            "policy": {
                "download": False,
                "default_mode": "execute" if self.config.execute else "preview_dry_run",
                "provider": self.config.provider,
                "evaluation_stage": self.config.evaluation_stage,
                "max_competitor_services": 1,
                "preserve_moi_containers": sorted(PROTECTED_MOI_CONTAINERS),
            },
            "packages": [candidate.public() for candidate in candidates],
            "units": public_units,
        }

    def _ensure_plan(self) -> dict[str, Any]:
        plan = self._plan()
        synced = self.store.sync_plan(plan)
        # Callers such as preflight use the returned plan directly; make it
        # observe the same restored unit identity and command paths written to
        # the checkpoint.
        plan["units"] = synced.get("units", plan["units"])
        return plan

    def _run_external(
        self,
        command: list[str],
        *,
        platform: str,
        action: str,
        allow_failure: bool = False,
    ) -> dict[str, Any]:
        if not self.config.execute:
            return {
                "status": "PREVIEW",
                "returncode": 0,
                "command": list(command),
                "platform": platform,
                "action": action,
            }
        env = load_campaign_env(self.config.repo_root, platform if platform in PLATFORM_ORDER else "dify_local")
        env.update(
            {
                "DEEPSEEK_BASE_URL": self.config.deepseek_base_url,
                "DEEPSEEK_LLM_MODEL": self.config.deepseek_llm_model,
                "MAAS_BASE_URL": self.config.maas_base_url,
                "MAAS_EMBEDDING_MODEL": self.config.maas_embedding_model,
                "MAAS_EMBEDDING_DIMENSION": str(self.config.maas_embedding_dimension),
                "COMPETITOR_EMBEDDING_PROVIDER": "maas",
            }
        )
        selected_provider = _command_option(command, "--text-llm-provider")
        if selected_provider is _MISSING:
            selected_provider = _command_option(command, "--llm-provider")
        if str(selected_provider).casefold() in {"deepseek", "deepseek-official", "dsv4f"}:
            # A stale selector must not override the frozen DeepSeek text
            # profile; MaaS remains embedding-only.
            env.pop("DIFY_QIANFAN_LLM_PROVIDER", None)
            env["COMPETITOR_TEXT_LLM_PROVIDER"] = "deepseek-official"
        try:
            completed = subprocess.run(
                command,
                cwd=self.config.repo_root,
                env=env,
                text=True,
                capture_output=True,
                check=False,
            )
        except OSError as exc:
            if allow_failure:
                return {
                    "status": "ERROR",
                    "returncode": 127,
                    "command": list(command),
                    "platform": platform,
                    "action": action,
                    "error": type(exc).__name__,
                    "stdout": "",
                }
            raise CampaignError(f"COMMAND_EXECUTION_FAILED:{action}:{type(exc).__name__}") from exc
        result = {
            "status": "SUCCESS" if completed.returncode == 0 else "ERROR",
            "returncode": int(completed.returncode),
            "command": list(command),
            "platform": platform,
            "action": action,
            "stdout": str(getattr(completed, "stdout", "") or ""),
        }
        if completed.returncode != 0 and not allow_failure:
            raise CampaignError(f"COMMAND_FAILED:{action}:exit-{completed.returncode}")
        return result

    def _invoke_runner(self, unit: Mapping[str, Any], stage: str, *, dry_run: bool) -> dict[str, Any]:
        runner_unit = CampaignUnit(
            ordinal=int(unit["ordinal"]),
            unit_id=str(unit["unit_id"]),
            dataset=str(unit["dataset"]),
            condition=str(unit["condition"]),
            platform=str(unit["platform"]),
            system=str(unit["system"]),
            package=Path(str(unit["package"])),
            manifest=Path(str(unit["manifest"])),
            run_id=str(unit["run_id"]),
            runner_output_root=Path(str(unit["runner_output_root"])),
            mllm_required=bool(unit.get("mllm_required", True)),
        )
        command = _runner_command(self.config, runner_unit, stage, dry_run=dry_run)
        result = self._run_external(command, platform=runner_unit.platform, action=f"runner-{stage}")
        parsed = _extract_result(result.get("stdout", ""))
        if not parsed.get("status") and not dry_run:
            summary = _load_json(runner_unit.runner_output_root / runner_unit.run_id / "summary.json")
            if isinstance(summary, Mapping):
                parsed = dict(_safe_public(summary))
        return {
            "status": parsed.get("status", result.get("status")),
            "returncode": result.get("returncode", 0),
            "run_id": parsed.get("run_id", runner_unit.run_id),
            "command": command,
            "result_keys": sorted(parsed.keys()),
        }

    def _invoke_judge(
        self,
        unit: Mapping[str, Any],
        *,
        command: str = "run",
        dry_run: bool,
    ) -> dict[str, Any]:
        judge_command = _judge_command(self.config, unit, command=command, dry_run=dry_run)
        result = self._run_external(
            judge_command,
            platform=str(unit["platform"]),
            action=f"judge-{command}",
            allow_failure=True,
        )
        summary_path = _unit_artifact_root(unit) / "judge" / "judge-summary.json"
        parsed: dict[str, Any] = {}
        if summary_path.is_file():
            summary = _load_json(summary_path)
            if isinstance(summary, Mapping):
                parsed = dict(_safe_public(summary))
        if not parsed:
            parsed = _extract_result(result.get("stdout", ""))
        return {
            "status": parsed.get("status", result.get("status")),
            "returncode": result.get("returncode", 0),
            "command": judge_command,
            "summary_path": str(summary_path),
            "result_keys": sorted(parsed.keys()),
            "errors": parsed.get("errors", []),
            "warnings": parsed.get("warnings", []),
            "denominator": parsed.get("denominator", {}),
        }

    def _invoke_provider_audit(
        self,
        unit: Mapping[str, Any],
        *,
        phase: str = "final",
    ) -> dict[str, Any]:
        audit_command = _provider_audit_command(self.config, unit, phase=phase)
        result = self._run_external(
            audit_command,
            platform=str(unit["platform"]),
            action="provider-audit-runner" if phase == "runner" else "provider-audit-final",
            allow_failure=True,
        )
        output_path = _unit_artifact_root(unit) / (
            "provider-audit-runner.json" if phase == "runner" else "provider-audit.json"
        )
        parsed: dict[str, Any] = {}
        if output_path.is_file():
            payload = _load_json(output_path)
            if isinstance(payload, Mapping):
                parsed = dict(_safe_public(payload))
        if not parsed:
            parsed = _extract_result(result.get("stdout", ""))
        return {
            "phase": phase,
            "status": parsed.get("status", result.get("status")),
            "returncode": result.get("returncode", 1),
            "command": audit_command,
            "output_path": str(output_path),
            "result_keys": sorted(parsed.keys()),
            "request_records": parsed.get("request_records", 0),
            "request_models": parsed.get("request_models_observed", []),
            "image_request_count": parsed.get("image_request_count", 0),
            "violations": parsed.get("violations", []),
        }

