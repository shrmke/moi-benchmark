def _resolve(root: Path, value: Path | str) -> Path:
    path = Path(value).expanduser()
    return path if path.is_absolute() else root / path


def _sha256_file(path: Path) -> str | None:
    if not path.is_file():
        return None
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _public_path(repo_root: Path, path: Path) -> str:
    resolved = path.expanduser().resolve()
    try:
        return resolved.relative_to(repo_root).as_posix()
    except ValueError:
        return str(resolved)


def _file_provenance(repo_root: Path, path: Path) -> dict[str, Any]:
    resolved = path.expanduser().resolve()
    return {
        "path": _public_path(repo_root, resolved),
        "present": resolved.is_file(),
        "sha256": _sha256_file(resolved),
    }


def _git_provenance(repo_root: Path) -> dict[str, Any]:
    try:
        head = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=False,
        )
        status = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError as exc:
        return {"status": "UNAVAILABLE", "error": type(exc).__name__}
    if head.returncode != 0 or status.returncode != 0:
        return {
            "status": "UNAVAILABLE",
            "head_returncode": head.returncode,
            "status_returncode": status.returncode,
        }
    status_text = status.stdout or ""
    return {
        "status": "PASS",
        "head": head.stdout.strip(),
        "dirty": bool(status_text.strip()),
        "dirty_path_count": len([line for line in status_text.splitlines() if line.strip()]),
        "status_sha256": hashlib.sha256(status_text.encode("utf-8")).hexdigest(),
    }


