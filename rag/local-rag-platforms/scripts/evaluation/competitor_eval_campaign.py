    def plan(self) -> dict[str, Any]:
        plan = self._ensure_plan()
        self.store.event("plan_created", unit_count=len(plan["units"]), missing_datasets=plan["missing_datasets"])
        return {**plan, "checkpoint": str(self.config.checkpoint), "progress_log": str(self.config.progress_log)}

    def preflight(self) -> dict[str, Any]:
        plan = self._ensure_plan()
        services: list[dict[str, Any]] = []
        used_platforms = [platform for platform in PLATFORM_ORDER if any(unit["platform"] == platform for unit in plan["units"])]
        for platform in used_platforms:
            spec = SERVICE_SPECS[platform]
            if not spec.managed:
                services.append({
                    "platform": platform,
                    "command": [],
                    "status": "SKIPPED",
                    "returncode": 0,
                    "material_exists": True,
                    "reason": "EXTERNAL_MOI_SERVICE",
                })
                continue
            command = (
                spec.compose_config_command(self.config.repo_root)
                if spec.compose_path is not None
                else ["bash", str(_resolve(self.config.repo_root, spec.launcher or MAXKB_LAUNCHER)), "verify-image"]
            )
            if self.config.execute:
                outcome = self._run_external(command, platform=platform, action="service-preflight", allow_failure=True)
                services.append({
                    "platform": platform,
                    "command": command,
                    "status": outcome["status"],
                    "returncode": outcome["returncode"],
                    "material_exists": self._service_material_exists(spec),
                })
            else:
                services.append({
                    "platform": platform,
                    "command": command,
                    "status": "PREVIEW",
                    "returncode": 0,
                    "material_exists": self._service_material_exists(spec),
                })

        runner_results: list[dict[str, Any]] = []
        for unit in plan["units"]:
            runner_result = self._invoke_runner(unit, "preflight", dry_run=not self.config.execute)
            judge_result = self._invoke_judge(
                unit,
                command="preflight",
                dry_run=not self.config.execute,
            )
            combined = {
                "unit_id": unit["unit_id"],
                "status": (
                    "BLOCKED"
                    if runner_result.get("status") not in {"SUCCESS", "PREVIEW", "DRY_RUN"}
                    or judge_result.get("status") not in {"READY", "DRY_RUN", "PREVIEW", "SUCCESS"}
                    else ("READY" if self.config.execute else "PREVIEW")
                ),
                "runner": runner_result,
                "judge": judge_result,
            }
            runner_results.append(combined)
            self.store.update_unit(unit["unit_id"], preflight=_safe_public(combined))

        status = "PREVIEW" if not self.config.execute else (
            "SUCCESS" if all(
                item["status"] in {"SUCCESS", "SKIPPED"}
                for item in services
            ) and all(item["status"] == "READY" for item in runner_results) else "BLOCKED"
        )
        self.store.data["status"] = status.casefold()
        self.store.write()
        self.store.event("preflight_complete", status=status, unit_count=len(runner_results))
        return {
            "schema": CHECKPOINT_SCHEMA,
            "status": status,
            "checkpoint": str(self.config.checkpoint),
            "services": services,
            "units": runner_results,
            "missing_datasets": plan["missing_datasets"],
        }

    def _service_material_exists(self, spec: ServiceSpec) -> bool:
        if not spec.managed:
            return True
        path = spec.compose_path or spec.launcher
        return bool(path and _resolve(self.config.repo_root, path).is_file())

    def _preview_run_commands(self, units: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
        commands: list[dict[str, Any]] = []
        previous: str | None = None
        for unit in units:
            if _campaign_unit_completed(unit):
                continue
            platform = str(unit["platform"])
            if previous != platform:
                if previous is not None:
                    previous_spec = SERVICE_SPECS[previous]
                    if previous_spec.managed:
                        commands.append({"action": "stop", "platform": previous, "command": previous_spec.stop_command(self.config.repo_root)})
                current_spec = SERVICE_SPECS[platform]
                if current_spec.managed:
                    commands.append({"action": "start", "platform": platform, "command": current_spec.start_command(self.config.repo_root)})
                else:
                    commands.append({"action": "external-service", "platform": platform, "command": [], "reason": "EXTERNAL_MOI_SERVICE"})
                previous = platform
            runner_unit = CampaignUnit(
                ordinal=int(unit["ordinal"]), unit_id=str(unit["unit_id"]), dataset=str(unit["dataset"]),
                condition=str(unit["condition"]), platform=platform, system=str(unit["system"]),
                package=Path(str(unit["package"])), manifest=Path(str(unit["manifest"])),
                run_id=str(unit["run_id"]), runner_output_root=Path(str(unit["runner_output_root"])),
                mllm_required=bool(unit.get("mllm_required", True)),
            )
            commands.append({
                "action": "runner-all",
                "platform": platform,
                "unit_id": unit["unit_id"],
                "command": _runner_command(self.config, runner_unit, "all", dry_run=True),
            })
            commands.append({
                "action": "provider-audit-runner",
                "platform": platform,
                "unit_id": unit["unit_id"],
                "command": _provider_audit_command(self.config, unit, phase="runner"),
            })
            commands.append({
                "action": "judge-run",
                "platform": platform,
                "unit_id": unit["unit_id"],
                "command": _judge_command(self.config, unit, command="run", dry_run=True),
            })
            commands.append({
                "action": "provider-audit-final",
                "platform": platform,
                "unit_id": unit["unit_id"],
                "command": _provider_audit_command(self.config, unit, phase="final"),
            })
            commands.append({
                "action": "metrics-aggregate",
                "platform": platform,
                "unit_id": unit["unit_id"],
                "command": _metrics_command(self.config, unit),
            })
        if previous is not None:
            previous_spec = SERVICE_SPECS[previous]
            if previous_spec.managed:
                commands.append({"action": "stop", "platform": previous, "command": previous_spec.stop_command(self.config.repo_root)})
        return commands

    def _validate_text_only_semantic_audit(self, plan: Mapping[str, Any]) -> None:
        """Fail closed before services start when the text-only audit is pending."""

        if not self.config.execute:
            return
        text_units = [
            unit for unit in plan.get("units", [])
            if isinstance(unit, Mapping) and bool(unit.get("mllm_required") is False)
        ]
        if not text_units:
            return
        signoff_path = self.config.text_only_semantic_audit
        if signoff_path is None:
            raise CampaignError("TEXT_ONLY_SEMANTIC_AUDIT_REQUIRED")
        payload = _load_json(signoff_path)
        if not isinstance(payload, Mapping) or payload.get("schema") != TEXT_ONLY_SEMANTIC_AUDIT_SCHEMA:
            raise CampaignError("TEXT_ONLY_SEMANTIC_AUDIT_SCHEMA_INVALID")
        if payload.get("status") != "PASS":
            raise CampaignError("TEXT_ONLY_SEMANTIC_AUDIT_NOT_PASS")
        if payload.get("mllm_required") is not False:
            raise CampaignError("TEXT_ONLY_SEMANTIC_AUDIT_MLLM_POLICY_INVALID")
        observed_hash = str(payload.get("manifest_sha256") or "").strip().casefold()
        if not observed_hash:
            raise CampaignError("TEXT_ONLY_SEMANTIC_AUDIT_MANIFEST_HASH_MISSING")
        expected_hashes: set[str] = set()
        for unit in text_units:
            manifest_path = Path(str(unit["manifest"]))
            if not manifest_path.is_file():
                raise CampaignError(f"TEXT_ONLY_SEMANTIC_AUDIT_MANIFEST_MISSING:{manifest_path}")
            expected_hashes.add(hashlib.sha256(manifest_path.read_bytes()).hexdigest())
        if observed_hash not in expected_hashes:
            raise CampaignError("TEXT_ONLY_SEMANTIC_AUDIT_MANIFEST_HASH_MISMATCH")

    def run(self) -> dict[str, Any]:
        plan = self._ensure_plan()
        self._validate_text_only_semantic_audit(plan)
        units = self.store.data.get("units", [])
        if not self.config.execute:
            preview = self._preview_run_commands(units)
            self.store.data["status"] = "dry_run"
            self.store.write()
            self.store.event("run_previewed", command_count=len(preview))
            return {
                "schema": CHECKPOINT_SCHEMA,
                "status": "DRY_RUN",
                "commands": preview,
                "units": units,
                "missing_datasets": plan["missing_datasets"],
                "checkpoint": str(self.config.checkpoint),
                "progress_log": str(self.config.progress_log),
            }

        controller = ServiceController(self)
        campaign_status = "SUCCESS"
        try:
            for unit in units:
                if _campaign_unit_completed(unit):
                    self.store.event("unit_resumed_completed", unit_id=unit["unit_id"], status=unit["status"])
                    continue
                unit_id = str(unit["unit_id"])
                previous_status = str(unit.get("status", "pending")).casefold()
                interrupted_resume = previous_status == "running" and int(unit.get("attempts", 0) or 0) > 0
                attempts = int(unit.get("attempts", 0) or 0) if interrupted_resume else int(unit.get("attempts", 0) or 0) + 1
                if attempts > 1 and not interrupted_resume:
                    base_run_id = str(unit.get("base_run_id") or unit["run_id"])
                    retry_run_id = f"{base_run_id}-attempt-{attempts}"
                    retry_artifact_root = str(Path(str(unit["runner_output_root"])) / retry_run_id)
                    self.store.update_unit(
                        unit_id,
                        base_run_id=base_run_id,
                        run_id=retry_run_id,
                        runner_artifact_root=retry_artifact_root,
                    )
                self.store.update_unit(unit_id, status="running", attempts=attempts, started_at=_utc_now(), error=None)
                self.store.event(
                    "unit_resumed_interrupted" if interrupted_resume else "unit_started",
                    unit_id=unit_id,
                    platform=unit["platform"],
                    dataset=unit["dataset"],
                    condition=unit["condition"],
                    run_id=unit["run_id"],
                )
                try:
                    controller.ensure(str(unit["platform"]))
                    runner_result = self._invoke_runner(
                        unit,
                        self.config.evaluation_stage,
                        dry_run=False,
                    )
                    runner_ok = int(runner_result.get("returncode", 1)) == 0 and _completed_status(runner_result.get("status"))
                    if not runner_ok:
                        self.store.update_unit(
                            unit_id,
                            status="blocked",
                            result={"runner": _safe_public(runner_result)},
                            completed_at=_utc_now(),
                        )
                        self.store.event("unit_blocked", unit_id=unit_id, status=runner_result.get("status"), stage="runner")
                        campaign_status = "BLOCKED"
                        break

                    provider_audit_initial_result = self._invoke_provider_audit(unit, phase="runner")
                    provider_audit_initial_ok = (
                        int(provider_audit_initial_result.get("returncode", 1)) == 0
                        and str(provider_audit_initial_result.get("status", "")).upper() == "PASS"
                    )
                    self.store.update_unit(
                        unit_id,
                        provider_audit_initial=_safe_public(provider_audit_initial_result),
                    )
                    self.store.event(
                        "provider_audit_completed",
                        unit_id=unit_id,
                        phase="runner",
                        status=provider_audit_initial_result.get("status"),
                    )
                    if not provider_audit_initial_ok:
                        self.store.update_unit(
                            unit_id,
                            status="blocked",
                            result={
                                "runner": _safe_public(runner_result),
                                "provider_audit_initial": _safe_public(provider_audit_initial_result),
                            },
                            completed_at=_utc_now(),
                        )
                        self.store.event(
                            "unit_blocked",
                            unit_id=unit_id,
                            status=provider_audit_initial_result.get("status"),
                            stage="provider-audit-runner",
                        )
                        campaign_status = "BLOCKED"
                        break

                    judge_result = self._invoke_judge(unit, command="run", dry_run=False)
                    judge_ok = int(judge_result.get("returncode", 1)) == 0 and str(judge_result.get("status", "")).upper() == "COMPLETE"
                    self.store.update_unit(unit_id, judge=_safe_public(judge_result))
                    self.store.event("judge_completed", unit_id=unit_id, status=judge_result.get("status"))
                    if not judge_ok:
                        self.store.update_unit(
                            unit_id,
                            status="blocked",
                            result={"runner": _safe_public(runner_result), "judge": _safe_public(judge_result)},
                            completed_at=_utc_now(),
                        )
                        self.store.event("unit_blocked", unit_id=unit_id, status=judge_result.get("status"), stage="judge")
                        campaign_status = "BLOCKED"
                        break

                    provider_audit_final_result = self._invoke_provider_audit(unit, phase="final")
                    provider_audit_final_ok = (
                        int(provider_audit_final_result.get("returncode", 1)) == 0
                        and str(provider_audit_final_result.get("status", "")).upper() == "PASS"
                    )
                    self.store.update_unit(
                        unit_id,
                        provider_audit=_safe_public(provider_audit_final_result),
                    )
                    self.store.event(
                        "provider_audit_completed",
                        unit_id=unit_id,
                        phase="final",
                        status=provider_audit_final_result.get("status"),
                    )
                    if not provider_audit_final_ok:
                        self.store.update_unit(
                            unit_id,
                            status="blocked",
                            result={
                                "runner": _safe_public(runner_result),
                                "provider_audit_initial": _safe_public(provider_audit_initial_result),
                                "judge": _safe_public(judge_result),
                                "provider_audit": _safe_public(provider_audit_final_result),
                            },
                            completed_at=_utc_now(),
                        )
                        self.store.event(
                            "unit_blocked",
                            unit_id=unit_id,
                            status=provider_audit_final_result.get("status"),
                            stage="provider-audit-final",
                        )
                        campaign_status = "BLOCKED"
                        break

                    metrics_result = self._invoke_metrics(unit)
                    metrics_ok = int(metrics_result.get("returncode", 1)) == 0 and str(metrics_result.get("status", "")).upper() == "COMPLETE"
                    self.store.update_unit(unit_id, metrics=_safe_public(metrics_result))
                    self.store.event("metrics_aggregated", unit_id=unit_id, status=metrics_result.get("status"))
                    unit_status = "completed" if metrics_ok else "blocked"
                    self.store.update_unit(
                        unit_id,
                        status=unit_status,
                        result={
                            "runner": _safe_public(runner_result),
                            "provider_audit_initial": _safe_public(provider_audit_initial_result),
                            "judge": _safe_public(judge_result),
                            "provider_audit": _safe_public(provider_audit_final_result),
                            "metrics": _safe_public(metrics_result),
                        },
                        completed_at=_utc_now(),
                    )
                    self.store.event(
                        "unit_completed" if unit_status == "completed" else "unit_blocked",
                        unit_id=unit_id,
                        status=metrics_result.get("status"),
                        stage="metrics",
                    )
                    if unit_status != "completed":
                        campaign_status = "BLOCKED"
                        break
                except CampaignError as exc:
                    self.store.update_unit(unit_id, status="blocked", error=str(exc), completed_at=_utc_now())
                    self.store.event("unit_blocked", unit_id=unit_id, reason=type(exc).__name__)
                    campaign_status = "BLOCKED"
                    break
        finally:
            try:
                controller.stop_active()
            except CampaignError as exc:
                campaign_status = "BLOCKED"
                self.store.event("service_stop_failed", reason=type(exc).__name__)

        self.store.data["status"] = campaign_status.casefold()
        self.store.write()
        self.store.event("run_complete", status=campaign_status)
        return {
            "schema": CHECKPOINT_SCHEMA,
            "status": campaign_status,
            "units": self.store.data.get("units", []),
            "missing_datasets": plan["missing_datasets"],
            "checkpoint": str(self.config.checkpoint),
            "progress_log": str(self.config.progress_log),
        }

    def status(self) -> dict[str, Any]:
        if not self.store.data:
            return {
                "schema": CHECKPOINT_SCHEMA,
                "status": "NOT_FOUND",
                "checkpoint": str(self.config.checkpoint),
                "progress_log": str(self.config.progress_log),
            }
        return {
            "schema": CHECKPOINT_SCHEMA,
            "status": str(self.store.data.get("status", "unknown")).upper(),
            "campaign_id": self.store.data.get("campaign_id"),
            "active_service": self.store.data.get("active_service"),
            "missing_datasets": self.store.data.get("missing_datasets", []),
            "units": self.store.data.get("units", []),
            "checkpoint": str(self.config.checkpoint),
            "progress_log": str(self.config.progress_log),
        }


