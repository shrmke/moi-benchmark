def _config_from_args(args: argparse.Namespace) -> CampaignConfig:
    command = str(getattr(args, "command", ""))
    repo_arg = getattr(args, "repo_root", _MISSING)
    repo_for_lookup = Path(ROOT if repo_arg is _MISSING else repo_arg).expanduser().resolve()
    checkpoint_arg = getattr(args, "checkpoint", _MISSING)
    checkpoint_for_lookup = _resolve(
        repo_for_lookup,
        DEFAULT_CHECKPOINT if checkpoint_arg is _MISSING else checkpoint_arg,
    )
    stored = _checkpoint_restore_values(checkpoint_for_lookup) if command == "run" else {}

    def value(name: str, default: Any) -> Any:
        explicit = getattr(args, name, _MISSING)
        if explicit is not _MISSING:
            return explicit
        return stored.get(name, default)

    # ``execute`` and ``download`` are command controls.  In particular,
    # execute is intentionally not restored: resuming a checkpoint must still
    # require the operator to opt into starting services and making requests.
    return CampaignConfig(
        repo_root=value("repo_root", ROOT),
        package_root=value("package_root", None),
        output_root=value("output_root", None),
        checkpoint=checkpoint_for_lookup,
        progress_log=value("progress_log", None),
        text_only_semantic_audit=value("text_only_semantic_audit", None),
        campaign_id=value("campaign_id", DEFAULT_CAMPAIGN_ID),
        execute=bool(getattr(args, "execute", False)),
        runner_path=value("runner_path", None),
        repeats=int(value("repeats", DEFAULT_REPEATS)),
        top_k=int(value("top_k", DEFAULT_TOP_K)),
        poll_seconds=float(value("poll_seconds", DEFAULT_POLL_SECONDS)),
        service_timeout=float(value("service_timeout", DEFAULT_SERVICE_TIMEOUT)),
        provider_timeout=float(value("provider_timeout", DEFAULT_PROVIDER_TIMEOUT)),
        upload_timeout=float(value("upload_timeout", DEFAULT_UPLOAD_TIMEOUT)),
        index_timeout=float(value("index_timeout", DEFAULT_INDEX_TIMEOUT)),
        query_timeout=float(value("query_timeout", DEFAULT_QUERY_TIMEOUT)),
        qa_timeout=float(value("qa_timeout", DEFAULT_QA_TIMEOUT)),
        provider=value("provider", DEFAULT_PROVIDER),
        text_llm_provider=value("text_llm_provider", DEFAULT_TEXT_LLM_PROVIDER),
        deepseek_base_url=value("deepseek_base_url", DEFAULT_DEEPSEEK_BASE_URL),
        deepseek_llm_model=value("deepseek_llm_model", DEFAULT_DEEPSEEK_LLM_MODEL),
        maas_base_url=value("maas_base_url", DEFAULT_MAAS_BASE_URL),
        maas_vl_model=value("maas_vl_model", DEFAULT_MAAS_VL_MODEL),
        maas_embedding_model=value("maas_embedding_model", DEFAULT_MAAS_EMBEDDING_MODEL),
        maas_embedding_dimension=int(value("maas_embedding_dimension", DEFAULT_MAAS_EMBEDDING_DIMENSION)),
        qa_concurrency=int(value("qa_concurrency", DEFAULT_QA_CONCURRENCY)),
        retrieval_concurrency=int(value("retrieval_concurrency", DEFAULT_RETRIEVAL_CONCURRENCY)),
        dify_max_indexing_scopes=int(value("dify_max_indexing_scopes", DEFAULT_DIFY_MAX_INDEXING_SCOPES)),
        fastgpt_ingest_concurrency=int(value("fastgpt_ingest_concurrency", DEFAULT_FASTGPT_INGEST_CONCURRENCY)),
        maxkb_ingest_concurrency=int(value("maxkb_ingest_concurrency", DEFAULT_MAXKB_INGEST_CONCURRENCY)),
        evaluation_stage=value("evaluation_stage", "all"),
        download=bool(getattr(args, "download", False)),
        judge_path=value("judge_path", None),
        metrics_path=value("metrics_path", None),
        judge_concurrency=int(value("judge_concurrency", DEFAULT_JUDGE_CONCURRENCY)),
        judge_retries=int(value("judge_retries", DEFAULT_JUDGE_RETRIES)),
        judge_timeout=float(value("judge_timeout", DEFAULT_JUDGE_TIMEOUT)),
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(list(argv) if argv is not None else None)
    try:
        orchestrator = CampaignOrchestrator(_config_from_args(args))
        result = getattr(orchestrator, args.command)()
        print(json.dumps(_safe_public(result), ensure_ascii=False, indent=2, sort_keys=True))
        return 0 if result.get("status") not in {"BLOCKED", "ERROR"} else 1
    except CampaignError as exc:
        print(json.dumps({"status": "ERROR", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
