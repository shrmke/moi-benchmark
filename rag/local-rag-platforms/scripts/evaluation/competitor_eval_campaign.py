def _unit_artifact_root(unit: Mapping[str, Any]) -> Path:
    value = unit.get("runner_artifact_root")
    if value:
        return Path(str(value)).expanduser()
    return Path(str(unit["runner_output_root"])).expanduser() / str(unit["run_id"])


def _provider_audit_command(
    config: CampaignConfig,
    unit: Mapping[str, Any],
    *,
    phase: str = "final",
) -> list[str]:
    if phase not in {"runner", "final"}:
        raise CampaignError(f"PROVIDER_AUDIT_PHASE_UNSUPPORTED:{phase}")
    run_root = _unit_artifact_root(unit)
    output_name = "provider-audit-runner.json" if phase == "runner" else "provider-audit.json"
    return [
        sys.executable,
        str(_resolve(config.repo_root, PROVIDER_AUDIT_PATH)),
        "--runs-root",
        str(run_root),
        "--output",
        str(run_root / output_name),
    ]


