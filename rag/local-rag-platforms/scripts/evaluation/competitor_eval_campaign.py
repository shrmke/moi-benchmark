    judge_concurrency: int = DEFAULT_JUDGE_CONCURRENCY
    judge_retries: int = DEFAULT_JUDGE_RETRIES
    judge_timeout: float = DEFAULT_JUDGE_TIMEOUT
    provider: str = DEFAULT_PROVIDER
    text_llm_provider: str = DEFAULT_TEXT_LLM_PROVIDER
    deepseek_base_url: str = DEFAULT_DEEPSEEK_BASE_URL
    deepseek_llm_model: str = DEFAULT_DEEPSEEK_LLM_MODEL
    maas_base_url: str = DEFAULT_MAAS_BASE_URL
    maas_vl_model: str = DEFAULT_MAAS_VL_MODEL
    maas_embedding_model: str = DEFAULT_MAAS_EMBEDDING_MODEL
    maas_embedding_dimension: int = DEFAULT_MAAS_EMBEDDING_DIMENSION
    qa_concurrency: int = DEFAULT_QA_CONCURRENCY
    retrieval_concurrency: int = DEFAULT_RETRIEVAL_CONCURRENCY
    dify_max_indexing_scopes: int = DEFAULT_DIFY_MAX_INDEXING_SCOPES
    fastgpt_ingest_concurrency: int = DEFAULT_FASTGPT_INGEST_CONCURRENCY
    maxkb_ingest_concurrency: int = DEFAULT_MAXKB_INGEST_CONCURRENCY
    evaluation_stage: str = "all"
    download: bool = False

    def __post_init__(self) -> None:
        repo = Path(self.repo_root).expanduser().resolve()
        object.__setattr__(self, "repo_root", repo)
        object.__setattr__(self, "package_root", _resolve(repo, self.package_root or Path(".local-services/competitor-eval-ready/v1")))
        object.__setattr__(self, "output_root", _resolve(repo, self.output_root or Path("runs/competitor-eval-campaign")))
        object.__setattr__(self, "checkpoint", _resolve(repo, self.checkpoint or Path(".local-services/competitor-eval-campaign/campaign.json")))
        progress = self.progress_log or (Path(self.checkpoint).parent / "progress.jsonl")
        object.__setattr__(self, "progress_log", _resolve(repo, progress))
        if self.text_only_semantic_audit is not None:
            object.__setattr__(self, "text_only_semantic_audit", _resolve(repo, self.text_only_semantic_audit))
        object.__setattr__(self, "runner_path", _resolve(repo, self.runner_path or Path("local-rag-platforms/scripts/evaluation/competitor_eval_runner.py")))
        object.__setattr__(self, "judge_path", _resolve(repo, self.judge_path or Path("local-rag-platforms/scripts/evaluation/competitor_eval_judge.py")))
        object.__setattr__(self, "metrics_path", _resolve(repo, self.metrics_path or Path("local-rag-platforms/scripts/evaluation/competitor_eval_metrics.py")))
        if self.repeats < 1 or self.top_k < 1:
            raise CampaignError("REPEATS_AND_TOP_K_MUST_BE_POSITIVE")
        if any(
            value < 1
            for value in (
                self.maas_embedding_dimension,
                self.qa_concurrency,
                self.retrieval_concurrency,
                self.dify_max_indexing_scopes,
                self.fastgpt_ingest_concurrency,
                self.maxkb_ingest_concurrency,
                self.judge_concurrency,
            )
        ):
            raise CampaignError("CAMPAIGN_CONCURRENCY_AND_DIMENSION_MUST_BE_POSITIVE")
        if self.judge_retries < 0 or self.judge_timeout <= 0:
            raise CampaignError("JUDGE_RETRIES_AND_TIMEOUT_INVALID")
        if self.download:
            raise CampaignError("DOWNLOAD_REFUSED: campaign consumes only already materialized local packages")
        if self.evaluation_stage not in {"all", "qa"}:
            raise CampaignError("EVALUATION_STAGE_MUST_BE_ALL_OR_QA")
        if self.provider != "hybrid" or self.text_llm_provider != "deepseek-official":
            raise CampaignError("DEEPSEEK_TEXT_MAAS_EMBEDDING_PROVIDER_REQUIRED")
        if self.deepseek_llm_model != DEFAULT_DEEPSEEK_LLM_MODEL:
            raise CampaignError(f"DEEPSEEK_TEXT_MODEL_REQUIRED:{DEFAULT_DEEPSEEK_LLM_MODEL}")
        if self.maas_embedding_model != DEFAULT_MAAS_EMBEDDING_MODEL or self.maas_embedding_dimension != DEFAULT_MAAS_EMBEDDING_DIMENSION:
            raise CampaignError(
                f"MAAS_ONLY_EMBEDDING_REQUIRED:{DEFAULT_MAAS_EMBEDDING_MODEL}/{DEFAULT_MAAS_EMBEDDING_DIMENSION}"
            )
        _validate_maas_base_url(self.maas_base_url, field="maas_config")
        _validate_deepseek_base_url(self.deepseek_base_url, field="deepseek_config")
        _reject_taas(
            (
                self.text_llm_provider,
                self.deepseek_base_url,
                self.deepseek_llm_model,
                self.maas_base_url,
                self.maas_vl_model,
                self.maas_embedding_model,
            ),
            field="maas_config",
        )


